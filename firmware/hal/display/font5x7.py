_FALLBACK_ROWS: tuple[str, ...] = (
    "11111", "10001", "10001", "10001", "10001", "10001", "11111"
)


def _rows_to_bits(rows: tuple[str, ...]) -> tuple[int, ...]:
    return tuple(int(row, 2) for row in rows)


_GLYPHS: dict[str, tuple[int, ...]] = {ch: _rows_to_bits(rows) for ch, rows in _ROWS.items()}
_FALLBACK_GLYPH: tuple[int, ...] = _rows_to_bits(_FALLBACK_ROWS)


def glyph_for(ch: str) -> tuple[int, ...]:
    """Return the glyph's 7 row-bitmasks (bit `GLYPH_W - 1` = leftmost
    column) for one character, accent-folding and case-folding before
    giving up and returning the fallback hollow-box glyph."""
    glyph = _GLYPHS.get(ch)
    if glyph is not None:
        return glyph
    upper = ch.upper()
    if upper != ch:
        glyph = _GLYPHS.get(upper)
        if glyph is not None:
            return glyph
    folded = unicodedata.normalize("NFKD", ch)
    base = "".join(c for c in folded if not unicodedata.combining(c))
    if base and base != ch:
        glyph = _GLYPHS.get(base) or _GLYPHS.get(base.upper())
        if glyph is not None:
            return glyph
    return _FALLBACK_GLYPH
